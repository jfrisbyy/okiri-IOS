function simpleHashForKeyword(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = ((hash << 5) - hash) + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

function normalizeText(s: string): string {
  return s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
}

export function getKeywordImage(text: string, hashSeed: string): string | null {
  const normalized = normalizeText(text);

  for (const entry of KEYWORD_IMAGE_MAP) {
    for (const keyword of entry.keywords) {
      const normalizedKeyword = normalizeText(keyword);
      if (normalized.includes(normalizedKeyword)) {
        const hash = simpleHashForKeyword(hashSeed + keyword);
        return entry.images[hash % entry.images.length];
      }
    }
  }

  return null;
}

