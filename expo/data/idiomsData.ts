export const getIdiomsByCategory = (category: IdiomCategory): FrenchIdiom[] => {
  return frenchIdioms.filter(idiom => idiom.category === category);
};

export const getRandomIdioms = (count: number): FrenchIdiom[] => {
  const shuffled = [...frenchIdioms].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
};

export const searchIdioms = (query: string): FrenchIdiom[] => {
  const lowerQuery = query.toLowerCase();
  return frenchIdioms.filter(idiom => 
    idiom.french.toLowerCase().includes(lowerQuery) ||
    idiom.meaning.toLowerCase().includes(lowerQuery) ||
    idiom.literal.toLowerCase().includes(lowerQuery)
  );
};
